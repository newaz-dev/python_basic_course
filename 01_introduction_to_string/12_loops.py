# We can implement loops by using range list and tuples
# Lets say we have a list named a
a = [1, 2, 3, 4, 5]

# LOOP structure:
for item in a:
    print(item)
# Now a item is present or not will be define by true or False
print(6 in a) #false
print(4 in a) #true

for i in range(101):
    print(f"Nasa is hacking: {i}%")
print("Nasa is Hacked")