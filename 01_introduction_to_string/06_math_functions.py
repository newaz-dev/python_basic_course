# =======Ceil, Floor, and Round=================#
import math
x = 10.5
print(f"X value is: {x}")
print(f"Floor value is {math.floor(x)}")
print(f"Ceilling value is {math.ceil(x)}")
y = 10.45
z = 10.59
print(f"Y value is: {y}")
print(f"rounded value of Y from 10.0 to 10.50 is: {round(y)}")
print(f"Z value is: {z}")
print(f"rounded value of Z from 10.51 to 10.99 is: {round(z)}")
